"""Windows release: a portable Orimbux Mothership.exe that needs no Python and no installation.
  python tools/package_pc.py VERSION OUTDIR          (on Windows, with: pip install pyinstaller pysdl2-dll pillow
                                                      and on Python >= 3.13 also audioop-lts)
-> OUTDIR/Orimbux Mothership/                  the folder as the player gets it:
     Orimbux Mothership.exe                    tools/pc/exe/launcher.py frozen with Python, SDL2.dll and audioop
     _internal/                                the frozen Python
     mothership/                               the app, exactly what the console gets (same files as package.py)
     LEIA-ME PC.txt
-> OUTDIR/OrimbuxMothership_VERSION_PC_Windows.zip   that folder, zipped"""
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import package  # noqa: E402

EXE = os.path.join(ROOT, "tools", "pc", "exe")
NAME = "Orimbux Mothership"


def icon(path):
    """the ship from docs/logo.png on a rounded night-sky tile; the small sizes show only the saucer"""
    from PIL import Image, ImageDraw
    logo = Image.open(os.path.join(ROOT, "docs", "logo.png")).convert("RGBA")
    void = logo.getpixel((0, 0))              # the logo's own night sky, so the crop has no visible edge

    def tile(size, crop, top):
        art = logo.crop(crop)
        k = size / float(art.width)
        art = art.resize((size, max(1, int(art.height * k))), Image.LANCZOS if size < art.width else Image.NEAREST)
        out = Image.new("RGBA", (size, size), void)
        out.paste(art, (0, int(top * size)))
        if crop[3] > 120:                     # the beam fades into the sky instead of stopping at the edge
            fade = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            d = ImageDraw.Draw(fade)
            y0 = int(size * 0.62)
            for y in range(y0, size):
                d.line([(0, y), (size, y)], fill=void[:3] + (int(255 * (y - y0) / float(size - y0)),))
            out = Image.alpha_composite(out, fade)
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius=size // 5, fill=255)
        out.putalpha(mask)
        return out

    big = tile(256, (192, 16, 448, 162), 0.2)                # the lettering starts just below y=162
    sizes = [(s, s) for s in (16, 24, 32, 48, 64, 128, 256)]
    small = [tile(s, (198, 24, 442, 118), 0.25) for s in (16, 24, 32, 48)]
    big.save(path, sizes=sizes, append_images=small)
    return path


def version_file(path, ver):
    nums = [int(n) for n in re.findall(r"\d+", ver)][:4]
    nums += [0] * (4 - len(nums))
    t = tuple(nums)
    text = """VSVersionInfo(
  ffi=FixedFileInfo(filevers=%(t)r, prodvers=%(t)r, mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
                    subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('041604b0', [
      StringStruct('CompanyName', 'Orimbux'),
      StringStruct('FileDescription', 'Orimbux Mothership'),
      StringStruct('FileVersion', %(v)r),
      StringStruct('InternalName', 'Orimbux Mothership'),
      StringStruct('LegalCopyright', 'MIT License'),
      StringStruct('OriginalFilename', 'Orimbux Mothership.exe'),
      StringStruct('ProductName', 'Orimbux Mothership'),
      StringStruct('ProductVersion', %(v)r)])]),
    VarFileInfo([VarStruct('Translation', [0x0416, 1200])])])
""" % {"t": t, "v": ver}
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


def freeze(work, dist, ver):
    """PyInstaller follows the app's imports (so every stdlib module it uses is frozen) but keeps only the
    standard library: the app itself and its pysdl2 stay plain files in mothership/. SDL2.dll goes in on its own
    (the launcher points PYSDL2_DLL_PATH at it): pysdl2-dll's module would drag pip along"""
    import sdl2dll
    sdl2 = os.path.join(os.path.dirname(sdl2dll.__file__), "dll", "SDL2.dll")
    mods = sorted(f[:-3] for f in os.listdir(package.APPD) if f.endswith(".py"))
    spec = os.path.join(work, "mothership.spec")
    with open(spec, "w", encoding="utf-8") as f:
        f.write("""# generated by tools/package_pc.py
import os
APPD = %(appd)r
a = Analysis([%(launcher)r], pathex=[APPD, os.path.join(APPD, "lib")], binaries=[(%(sdl2)r, ".")],
             hiddenimports=%(mods)r + ["sdl2"],
             excludes=["sdl2dll", "pip", "setuptools", "pkg_resources", "tkinter", "unittest", "pydoc", "numpy", "PIL"])
inside = os.path.normcase(APPD) + os.sep
a.pure = [e for e in a.pure if not os.path.normcase(e[1] or "").startswith(inside)]
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [("X utf8", None, "OPTION")], exclude_binaries=True, name=%(name)r,
          console=False, icon=%(icon)r, version=%(ver)r, upx=False)
coll = COLLECT(exe, a.binaries, a.datas, name=%(name)r, upx=False)
""" % {"appd": package.APPD, "launcher": os.path.join(EXE, "launcher.py"), "sdl2": sdl2, "mods": mods,
       "name": NAME, "icon": icon(os.path.join(work, "icon.ico")),
       "ver": version_file(os.path.join(work, "version.txt"), ver)})
    subprocess.check_call([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
                           "--workpath", os.path.join(work, "pyi"), "--distpath", dist, spec])
    return os.path.join(dist, NAME)


def main():
    ver, outd = sys.argv[1], os.path.abspath(sys.argv[2])
    work = os.path.join(outd, "pc-build")
    os.makedirs(work, exist_ok=True)
    folder = os.path.join(outd, NAME)
    if os.path.isdir(folder):
        shutil.rmtree(folder)
    built = freeze(work, os.path.join(work, "dist"), ver)
    shutil.copytree(built, folder)
    for p, arc in package.files():                          # mothership/...: no saves, no player files
        dst = os.path.join(folder, arc)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(p, dst)
    shutil.copy2(os.path.join(ROOT, "LEIA-ME.txt"), os.path.join(folder, "mothership", "LEIA-ME.txt"))
    shutil.copy2(os.path.join(EXE, "LEIA-ME PC.txt"), os.path.join(folder, "LEIA-ME PC.txt"))
    zpath = os.path.join(outd, "OrimbuxMothership_%s_PC_Windows.zip" % ver)
    n = 0
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for root, dirs, fs in os.walk(folder):
            dirs.sort()
            for f in sorted(fs):
                p = os.path.join(root, f)
                z.write(p, os.path.join(NAME, os.path.relpath(p, folder)))
                n += 1
    print("folder:", folder)
    print("zip:", zpath, "%.1f MB, %d files" % (os.path.getsize(zpath) / 1e6, n))


if __name__ == "__main__":
    main()
